#!/bin/bash


set -e

echo "=========================================="
echo "运行所有测试..."
echo "=========================================="

# 检查 Maven
if ! command -v mvn &> /dev/null; then
    echo "错误: 未找到 Maven"
    exit 1
fi

# 运行测试
mvn clean test

echo ""
echo "=========================================="
echo "测试完成！"
echo "=========================================="